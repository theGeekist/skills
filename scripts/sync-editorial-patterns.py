#!/usr/bin/env python3
"""Generate a contextual editorial reference from original, attributed examples."""
import argparse
import json
import os
from pathlib import Path
import re
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
FIELDS = ('id', 'name', 'concern', 'severity', 'source_facts', 'before', 'after', 'reason', 'exception')


def validate(data):
    if not isinstance(data, dict) or type(data.get('version')) is not int or data['version'] != 1:
        raise ValueError('expected editorial pattern schema version 1')
    if not isinstance(data.get('purpose'), str) or not data['purpose'].strip():
        raise ValueError('purpose must be non-empty text')
    sources = data.get('sources')
    if not isinstance(sources, dict) or not sources:
        raise ValueError('sources must be a non-empty object')
    for source_id, source in sources.items():
        if not isinstance(source_id, str) or not re.fullmatch(r'[a-z]+(?:-[a-z]+)*', source_id):
            raise ValueError('invalid source identifier')
        if not isinstance(source, dict):
            raise ValueError(f'{source_id}: source must be an object')
        for field in ('title', 'url', 'application'):
            if not isinstance(source.get(field), str) or not source[field].strip():
                raise ValueError(f'{source_id}: {field} must be non-empty text')
        if not re.fullmatch(r'https://[^\s]+', source['url']):
            raise ValueError(f'{source_id}: source URL must use HTTPS')
    patterns = data.get('patterns')
    if not isinstance(patterns, list) or not patterns:
        raise ValueError('patterns must be a non-empty array')
    seen = set()
    for pattern in patterns:
        if not isinstance(pattern, dict):
            raise ValueError('pattern must be an object')
        for field in FIELDS:
            if not isinstance(pattern.get(field), str) or not pattern[field].strip():
                raise ValueError(f'pattern {field} must be non-empty text')
        identifier = pattern['id']
        if not re.fullmatch(r'E[0-9]{3}', identifier):
            raise ValueError(f'{identifier}: expected a stable E000-style identifier')
        if identifier in seen:
            raise ValueError(f'{identifier}: duplicate pattern identifier')
        seen.add(identifier)
        if pattern['severity'] not in ('material', 'contextual'):
            raise ValueError(f'{identifier}: severity must be material or contextual')
        if pattern['before'] == pattern['after']:
            raise ValueError(f'{identifier}: example must show a revision')
        refs = pattern.get('sources')
        if not isinstance(refs, list) or not refs or any(not isinstance(value, str) for value in refs):
            raise ValueError(f'{identifier}: sources must name at least one attribution')
        if len(refs) != len(set(refs)) or any(value not in sources for value in refs):
            raise ValueError(f'{identifier}: sources contain an unknown or duplicate attribution')
    return data


def load_patterns(root):
    return validate(json.loads((root / 'standards/editorial-patterns.json').read_text()))


def render(data):
    rows = []
    sections = []
    for pattern in sorted(data['patterns'], key=lambda value: value['id']):
        identifier = pattern['id']
        rows.append(f"| [{identifier}: {pattern['name']}](#{identifier.lower()}) | {pattern['concern']} | {pattern['severity'].capitalize()} |")
        source_links = ', '.join(f"[{data['sources'][key]['title']}]({data['sources'][key]['url']})" for key in pattern['sources'])
        sections.append(f'''<a id="{identifier.lower()}"></a>
## {identifier}: {pattern['name']}

**Review priority:** {pattern['severity'].capitalize()}. **Concern:** {pattern['concern']}.

**Invented source facts:** {pattern['source_facts']}

**Before**

> {pattern['before']}

**After**

> {pattern['after']}

**Why this edit helps:** {pattern['reason']}

**When to keep a different form:** {pattern['exception']}

**Related guidance:** {source_links}.
''')
    source_notes = '\n'.join(f"- [{source['title']}]({source['url']}): {source['application']}" for source in data['sources'].values())
    return '''<!-- Generated by scripts/sync-editorial-patterns.py; edit standards/editorial-patterns.json. -->
# Review consequential editorial patterns

Use the relevant example during a detailed edit. Start from the actual source and reader's purpose; a matching phrase alone does not establish a defect. These original examples do not add domain rules to a real project.

Material findings change a fact, condition, accepted meaning or authorised action. Contextual findings depend on the audience, document type and author voice. Review priority is an editorial judgement, not an automated score.

| Pattern | Concern | Review priority |
| --- | --- | --- |
''' + '\n'.join(rows) + '\n\n' + '\n'.join(sections) + '''
## Sources and local adaptation

The examples and explanations in this reference are original local writing. Stable identifiers and explicit exceptions make findings easier to inspect and discuss. No external pattern catalogue or revision template is copied.

''' + source_notes + '''

This reference supports source-based editing. It does not detect AI authorship, verify claims automatically or require every example to be loaded for a small change.
'''


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='report generated reference drift without writing')
    args = parser.parse_args(argv)
    try:
        text = render(load_patterns(ROOT))
        target = ROOT / 'standards/editorial-patterns.md'
        changed = not target.is_file() or target.read_text() != text
        if changed and not args.check:
            temporary = None
            try:
                with tempfile.NamedTemporaryFile(dir=target.parent, mode='w', delete=False) as output:
                    temporary = output.name
                    output.write(text)
                os.chmod(temporary, 0o644)
                os.replace(temporary, target)
            finally:
                if temporary and os.path.exists(temporary):
                    os.unlink(temporary)
        print(json.dumps({'mode': 'check' if args.check else 'sync', 'changed': ['standards/editorial-patterns.md'] if changed else []}))
        return int(args.check and changed)
    except (OSError, ValueError, TypeError, KeyError) as error:
        print(json.dumps({'error': str(error)}))
        return 2


if __name__ == '__main__':
    sys.exit(main())
