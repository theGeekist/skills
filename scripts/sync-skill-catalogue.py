#!/usr/bin/env python3
"""Generate human skill overviews and client presentation from one catalogue.

Activation descriptions remain authored in SKILL.md. They are checked against
this catalogue rather than rewritten by a presentation generator.
"""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent


def activation_description(text):
    frontmatter = text.split('---', 2)[1]
    match = re.search(r'^description: (.+)$', frontmatter, re.M)
    if not match:
        raise ValueError('expected a single-line skill activation description')
    value = match.group(1)
    return json.loads(value) if value.startswith('"') else value


def load_catalogue(root):
    data = json.loads((root / 'standards/skill-catalogue.json').read_text())
    if data.get('version') != 1 or not re.fullmatch(r'v\d+\.\d+\.\d+', data.get('release', '')):
        raise ValueError('invalid catalogue schema version or release')
    names = {p.parent.name for p in (root / 'skills').glob('*/SKILL.md')}
    if names != set(data.get('skills', {})):
        raise ValueError('catalogue must cover exactly the installed skill directories')
    for name, skill in data['skills'].items():
        if activation_description((root / 'skills' / name / 'SKILL.md').read_text()) != skill['activation_description']:
            raise ValueError(f'{name}: activation description differs; review intent before updating the catalogue')
        reference = skill['reference']
        if Path(reference).name != reference or not reference.endswith('.md'):
            raise ValueError(f'{name}: source reference must stay inside the skill references directory')
        if not (root / 'skills' / name / 'references' / reference).is_file():
            raise ValueError(f'{name}: missing bundled source reference')
        if not 25 <= len(skill['interface']['short_description']) <= 64:
            raise ValueError(f'{name}: short description must contain 25–64 characters')
        skill_root = (root / 'skills' / name).resolve()
        for field in ('icon_small', 'icon_large'):
            declared = Path(skill['interface'][field].removeprefix('./'))
            icon = (skill_root / declared).resolve()
            if declared.is_absolute() or not icon.is_relative_to(skill_root):
                raise ValueError(f'{name}: declared icon must stay inside the skill directory')
            if not icon.is_file():
                raise ValueError(f'{name}: missing declared icon')
        expected_policy = False if name == 'write-project-content' else None
        if skill['allow_implicit_invocation'] is not expected_policy:
            raise ValueError(f'{name}: unexpected implicit invocation policy')
        if not skill['sources'] or any(not source['url'].startswith('https://') for source in skill['sources']):
            raise ValueError(f'{name}: expected primary source links')
    groupings = data.get('directory', {}).get('groupings', [])
    grouped = []
    for group in groupings:
        if not group.get('title') or not group.get('description') or not group.get('skills'):
            raise ValueError('directory groups require a title, description and skills')
        grouped.extend(group['skills'])
    if len(grouped) != len(set(grouped)) or set(grouped) != names:
        raise ValueError('directory groups must cover every skill exactly once')
    return data


def overview(name, skill, data):
    source_list = '\n'.join(f"- [{source['label']}]({source['url']})" for source in skill['sources'])
    return f'''<!-- Generated by scripts/sync-skill-catalogue.py; edit standards/skill-catalogue.json. -->
# {skill['title']}

{skill['purpose']}

[All skills](index.md) · [Collection overview](../../README.md) · [Research and inspiration](../../standards/framework-evidence.md)

## When to use it

{skill['when_to_use']}

Example request:

> {skill['example_request']}

Expected result: {skill['expected_result']}

## A concrete example

This illustrative example starts from the source facts below.

**Source facts and constraints:** {skill['example']['source_facts']}

**Before**

> {skill['example']['before']}

**After**

> {skill['example']['after']}

## Install and use

Install this skill from the versioned collection in a supported Agent Skills environment:

```sh
npx skills add {data['repository']}/tree/{data['release']} --skill {name}
```

Select the intended agent and installation scope when prompted. This CLI installation is separate from ChatGPT plugin registration and mobile availability. Client discovery and activation require their own verification.

Read the [complete skill instructions](../../skills/{name}/SKILL.md) and [bundled purpose reference](../../skills/{name}/references/{skill['reference']}) for the full conditions and exceptions.

## Practices behind this skill

{skill['source_basis']}

{source_list}

The [source-to-guidance map](../../standards/framework-evidence.md) explains how these sources inform the skill and which decisions are local.

## Follow the work

- [Walk through all eleven skills](../language-system/skill-walkthrough.md)
- [Original research](../language-system/research-baseline.md) and [framework evaluation](../language-system/framework-evaluation.md)
- [Compare existing writing skills](../language-system/competing-writing-skills.md)
- [Validation and evidence](../language-system/validation-results.md)
'''


def render(root, data):
    planned = {}
    for name, skill in sorted(data['skills'].items()):
        interface = '\n'.join(f'  {key}: {json.dumps(value, ensure_ascii=False)}' for key, value in skill['interface'].items())
        yaml = 'interface:\n' + interface + '\n'
        if skill['allow_implicit_invocation'] is False:
            yaml += '\npolicy:\n  allow_implicit_invocation: false\n'
        planned[root / 'skills' / name / 'agents/openai.yaml'] = yaml
        planned[root / 'docs/skills' / (name + '.md')] = overview(name, skill, data)
    rows = '\n'.join(f"| [{skill['title']}]({name}.md) | {skill['purpose']} |" for name, skill in sorted(data['skills'].items()))
    planned[root / 'docs/skills/index.md'] = f'''<!-- Generated by scripts/sync-skill-catalogue.py; edit standards/skill-catalogue.json. -->
# Choose a Geekist skill

Choose by the work you need to do. Each page shows an example request, expected result, before/after example, sources and a versioned install command. Skills can be used separately; this is not an eleven-step prerequisite.

| Skill overview | Purpose |
| --- | --- |
{rows}

See the [connected walkthrough](../language-system/skill-walkthrough.md), [source map](../../standards/framework-evidence.md) and [comparison with existing writing skills](../language-system/competing-writing-skills.md) for the reasoning behind the collection.
'''
    planned[root / 'skills.sh.json'] = json.dumps({
        '$schema': 'https://skills.sh/schemas/skills.sh.schema.json',
        'notGrouped': 'bottom',
        'groupings': data['directory']['groupings'],
    }, indent=2, ensure_ascii=False) + '\n'
    for manifest in ('.codex-plugin/plugin.json', '.claude-plugin/plugin.json'):
        path = root / manifest
        document = json.loads(path.read_text())
        document['homepage'] = data['plugin']['homepage']
        document['description'] = data['plugin']['description']
        document['keywords'] = data['plugin']['keywords']
        if 'interface' in document:
            document['interface'].update({
                'websiteURL': data['plugin']['homepage'],
                'displayName': data['plugin']['display_name'],
                'shortDescription': data['plugin']['short_description'],
                'longDescription': data['plugin']['long_description'],
                'defaultPrompt': data['plugin']['default_prompts'],
            })
        planned[path] = json.dumps(document, indent=2, ensure_ascii=False) + '\n'
    marketplace_path = root / '.claude-plugin/marketplace.json'
    marketplace = json.loads(marketplace_path.read_text())
    marketplace['description'] = data['plugin']['description']
    for entry in marketplace['plugins']:
        if entry['name'] == 'geekist-architecture-skills':
            entry['description'] = data['plugin']['description']
    planned[marketplace_path] = json.dumps(marketplace, indent=2, ensure_ascii=False) + '\n'
    return planned


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='report generated presentation drift without writing')
    args = parser.parse_args(argv)
    try:
        data = load_catalogue(ROOT)
        planned = render(ROOT, data)
        changed = [str(path.relative_to(ROOT)) for path, text in planned.items() if not path.is_file() or path.read_text() != text]
        if not args.check:
            for path, text in planned.items():
                if str(path.relative_to(ROOT)) in changed:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(text)
        print(json.dumps({'mode': 'check' if args.check else 'sync', 'changed': changed}))
        return int(args.check and bool(changed))
    except (OSError, ValueError, KeyError, TypeError, IndexError) as error:
        print(json.dumps({'error': str(error)}))
        return 2


if __name__ == '__main__':
    sys.exit(main())
